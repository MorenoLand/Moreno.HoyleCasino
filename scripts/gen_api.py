# gen_api.py: turn api_table.json and gl_table.json into rt/api_gen.c (static import table + name->argument-count list).
import json
import os
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import cfg

HERE = os.path.dirname(os.path.abspath(__file__))
api = json.load(open(os.path.join(cfg.DATA, "api_table.json"), encoding="utf-8"))
gl = json.load(open(os.path.join(cfg.DATA, "gl_table.json"), encoding="utf-8"))

names = {}
for e in api:
    if e["nargs"] is not None:
        names[e["name"]] = e["nargs"]
for e in gl["core"] + gl["extensions"]:
    if e.get("nargs") is not None:
        names[e["name"]] = e["nargs"]

# GLU and anything else loaded at run time from glu32/gdi32 etc.: read the mingw import libraries
env = dict(os.environ)
MINGW = cfg.mingw32()
env["PATH"] = os.path.join(MINGW, "bin") + os.pathsep + env["PATH"]
for lib in ("libglu32.a", "libopengl32.a", "libkernel32.a", "libuser32.a", "libgdi32.a", "libwinmm.a", "libimm32.a", "libcomctl32.a", "libcomdlg32.a", "libversion.a"):
    path = os.path.join(MINGW, "lib", lib)
    if not os.path.exists(path):
        continue
    out = subprocess.run([os.path.join(MINGW, "bin", "nm.exe"), "-g", path], capture_output=True, text=True, env=env).stdout
    for line in out.splitlines():
        p = line.split()
        if len(p) == 3 and p[1] in ("T", "I") and p[2].startswith("_") and "@" in p[2]:
            nm, n = p[2][1:].rsplit("@", 1)
            if n.isdigit() and nm not in names:
                names[nm] = int(n) // 4

with open(os.path.join(cfg.RT, "api_gen.c"), "w", encoding="utf-8") as o:
    o.write('/* generated by gen_api.py: do not edit */\n#include "api.h"\n\nconst ApiStatic api_static[] = {\n')
    for e in api:
        o.write('    {0x%s, "%s", "%s", %s, %d},\n' % (e["ea"].replace("0x", ""), e["module"], e["name"], e["nargs"] if e["nargs"] is not None else -1, 1 if e["conv"] == "cdecl" else 0))
    o.write("};\nconst int api_static_n = %d;\n\nconst NameArgs name_args[] = {\n" % len(api))
    for k in sorted(names):
        o.write('    {"%s", %d},\n' % (k, names[k]))
    o.write("};\nconst int name_args_n = %d;\n" % len(names))
print("api entries %d, names %d" % (len(api), len(names)))
